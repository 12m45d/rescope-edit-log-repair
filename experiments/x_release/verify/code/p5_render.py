#!/usr/bin/env python3
"""Part 5: out/table.txt rendered from out/verdicts.json (nothing is computed here)."""
import collections
import json
import os
import time

V = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
v = json.load(open(V + "/out/verdicts.json"))
L = []
P = L.append


def num(x):
    if x is None:
        return "-"
    if isinstance(x, str):
        return x
    if isinstance(x, bool):
        return str(x)
    if isinstance(x, int):
        return str(x)
    return f"{x:.6g}"


def table(head, rows, indent="  "):
    w = [max(len(str(r[i])) for r in [head] + rows) for i in range(len(head))]
    P(indent + "  ".join(str(h).ljust(w[i]) for i, h in enumerate(head)))
    P(indent + "  ".join("-" * w[i] for i in range(len(head))))
    for r in rows:
        P(indent + "  ".join(str(c).ljust(w[i]) for i, c in enumerate(r)))


M = v["macros"]
rc = [r for r in M if r["recomputed"]]
P(f"X_RELEASE / VERIFY   rendered {time.strftime('%Y-%m-%d %H:%M:%S')} by code/p5_render.py from out/verdicts.json")
P("Independent recomputation of the fix-up read-outs (e1_main, e2_curves, e3_qwen, e3_llava: out/fixup; x_release/out) that the paper and the technical report print.")
P("Own code (code/vlib.py, p1 .. p6); CPU; no model run; rows read with gzip + json; no function of the experiments computes a number here")
P("(p6 uses fx.logs.open for DATA ACCESS only: pool rows and query ids of the two development logs).")
P("")
P("TOLERANCES")
for k, t in v["tolerances"].items():
    P(f"  {k}: {t}")
P("")
P("1. MACROS whose manifest entry reads one of the five directories (copies of numbers_manifest.json / vlm_macros.py / numbers.tex / vlm_facts.json: verify/copies)")
by = collections.Counter(r["printed_in"] for r in M)
P(f"  listed {len(M)}: body {by['body']}, report only {by['report']}, generated by the family of Table tab:logs for logs without a row (printed nowhere) {by['unused']}")
P(f"  recomputed {len(rc)}; agreeing {sum(1 for r in rc if r['agree'])}; disagreeing {sum(1 for r in rc if not r['agree'])}; not recomputed {len(M) - len(rc)}")
P(f"  the printed string (numbers.tex) equals my value under the paper's printing rule: {sum(1 for r in rc if r['printed_agrees'])}; differs: {sum(1 for r in rc if r['printed_agrees'] is False)}; "
  f"interval ends from other resamples (not comparable digit by digit): {sum(1 for r in rc if r['printed_agrees'] is None)}")
P("")
table(["macro", "where", "key", "stored", "mine", "paper prints", "mine prints", "agree"],
      [[r["name"], r["printed_in"] + (" (" + ",".join(f.replace(".tex", "") for f in r["tex_files"]) + ")" if r["tex_files"] else ""), r["key"][:46], num(r["stored"]), num(r["mine"]),
        num(r["paper_prints"]), num(r["mine_as_printed"]), ("yes" if r["agree"] else "NO") + ("" if r["agreement"] == "exact" else " (MC)")] for r in M])
P("")
P("  (MC): interval end of a bootstrap, my own resamples; agreement = within 0.25 x bootstrap SE:")
for r in M:
    if r["agreement"] != "exact":
        n = r["note"]
        P(f"    {r['name']}: stored {r['stored']:.4f}, mine {r['mine']:.4f}, difference {n['difference']:.4f} = {n['difference_in_se']:.3f} SE (allowed {n['allowed_difference']:.4f})")
P("")
P("2. PAPER NUMBERS OF THE FIX-UPS BEHIND GENERATED TABLE BODIES (no macro; the table generator reads the key)")
T = v["table_numbers"]
g = collections.OrderedDict()
for t in T:
    a = g.setdefault((t["table"], t["printed_in"]), [0, 0, 0])
    a[0] += 1
    a[1] += bool(t["recomputed"])
    a[2] += bool(t["agree"])
table(["table", "printed in", "numbers", "recomputed", "agree"], [[k[0], k[1], a[0], a[1], a[2]] for k, a in g.items()])
ro = [t for t in T if t["printed_in"] == "report"]
P(f"  only the report prints: {len(ro)} recomputed, {sum(bool(t['agree']) for t in ro)} agree (+ the {by['report']} report-only macros of part 1)")
ie = [t for t in T if "difference_in_se" in t]
P(f"  bootstrap interval ends among them: {len(ie)}; reproduced exactly by my replication of the experiment's 2000 resamples: {sum(bool(t['agree']) for t in ie)}; "
  f"my own 20000 resamples inside the allowance: {sum(bool(t['within_monte_carlo_error']) for t in ie)}; largest difference {max(t['difference_in_se'] for t in ie):.3f} SE")
P("")
P("  Paired differences on the unseen logs of the SECOND backbone (LLaVA; Table tab:app:repl of the report): stored value [interval] | interval of my own resamples")
rows = []
d = {t["name"]: t for t in T if t["table"] == "tab_vlm_tr_repl" and t["name"].startswith("EthreeFxL")}
for stem in sorted({k[:-4] if k.endswith("Diff") else k[:-2] for k in d}):
    if stem + "Diff" not in d:
        continue
    a, lo, hi = d[stem + "Diff"], d[stem + "Lo"], d[stem + "Hi"]
    rows.append([stem.replace("EthreeFx", ""), f"{a['stored']:+.2f} [{lo['stored']:+.2f}, {hi['stored']:+.2f}]", f"{a['mine']:+.2f} [{lo['own_resamples_value']:+.2f}, {hi['own_resamples_value']:+.2f}]",
                 "yes" if a["agree"] and lo["agree"] and hi["agree"] and lo["within_monte_carlo_error"] and hi["within_monte_carlo_error"] else "NO"])
table(["log + read-out", "stored", "mine (own resamples)", "agree"], rows, indent="    ")
o = v["other_recomputed_fixup_numbers"]
P("")
P(f"  All fix-up paper numbers recomputed on the way (printed or not): {o['n']}; agreeing: {o['n_agree']}; differing: {len(o['differ'])}")
P("")
P("3. 'CHANGED WITHOUT A RELEASE: 0'  (a row counts if no edit is released on it and its D1 flag is set; pools heldout_disjoint + HN-I + HN-Q + HN-X, summed over the runs)")
c = v["changed_without_a_release"]
table(["log | thresholds-only row", "rows without a release", "of them changed", "source of these rows"],
      [[k, x["rows_without_a_release"], x["of_them_changed"], json.dumps(x["src_of_these_rows"])] for k, x in c["thresholds_only_rows"].items()])
P("  gates at the last prompt position, all 13 logs:")
table(["method", "rows without a release", "of them changed", "source of these rows"],
      [[k, x["rows_without_a_release"], x["of_them_changed"], json.dumps(x["src_of_these_rows"])] for k, x in c["gates_at_the_last_position"].items()], indent="    ")
P("  " + c["reading"])
P("")
P("4. THE THREE STATEMENTS IN WORDS")
for k in "abc":
    s = v["statements"][k]
    P(f"  ({k}) {s['statement']}")
    P(f"      VERDICT: {s['verdict']}")
P("")
P("  (a) ReScope on near-scope negatives of the development logs: changed among the released, per behavioural draw")
table(["log, kind", "released by draw", "changed among them", "% by draw", "mean of draws", "pooled"],
      [[k, x["released_by_draw"], x["changed_among_them_by_draw"], "/".join(f"{y:.1f}" for y in x["by_draw"]), f"{x['mean_over_draws']:.2f}", f"{x['pooled_over_draws']:.2f}"]
       for k, x in v["statements"]["a"]["near_scope"].items()], indent="    ")
b = v["statements"]["b"]
P("  (b) per log: release on held-out probes that ask an edit's question (behaviour, %), calibration draws of 20 above 5 / 101")
table(["log", "near release %", "draws above"], [[l, f"{b['near_release_percent_by_log'][l]:.2f}", b["draws_above_by_log"][l]] for l in b["near_release_percent_by_log"]], indent="    ")
P("  (c) Holm over the unseen logs: rejected / against ReScope / in its favour")
rows = []
for h in ("H2", "H3"):
    x = v["statements"]["c"][h]
    for tag, lab in (("stored", "stored p values"), ("replicated", "my replication of the experiment's 2000 resamples"), ("own_precise", "my own resamples, pooled (20000; 820000 near the limit)"),
                     ("own_20000", "my own first 20000 resamples")):
        rows.append([h, x["family"], lab, x[tag]["rejected"], x[tag]["worse"], x[tag]["better"]])
table(["read-out", "family", "p values from", "rejected", "against", "in favour"], rows, indent="    ")
P("    members closest to the limit 0.05 (Holm-adjusted):")
for h in ("H2", "H3"):
    for m in v["statements"]["c"][h]["closest_to_0_05"]:
        P(f"      {h}  {m['member']}: stored p {m['stored_p']:.4f} -> Holm {m['holm_stored']:.4f}; own p {m['own_p']:.5f} +- {m['own_p_mc_se']:.5f} ({m['own_p_resamples']} resamples) -> Holm {m['holm_own_precise']:.4f}; "
          f"own first 20000 resamples -> Holm {m['holm_own_20000']:.4f}")
P("")
P("5. SIDE CHECKS")
P("  H1, 'Holm p <= 0.002' (Sec. 5.2): 4 tests x 1 / 2000; my own bootstrap (streams x query clusters, 20000 resamples) of the four differences:")
for k, x in v["h1_holm"]["tests"].items():
    P(f"    {k} ({x['linear_repair']}): {x['value']:.2f} [{x['ci_lo']:.2f}, {x['ci_hi']:.2f}], resamples on the other side of 0: {x['n_other_side']} of {x['n_boot']}; stored {x['stored_difference']:.2f} "
      f"[{x['stored_ci'][0]:.2f}, {x['stored_ci'][1]:.2f}], Holm {x['stored_p_holm']}")
r = v["report_caption_tab_app_repl"]
P("  caption of Table tab:app:repl (report): largest mean number of edits at their cap under the raised scale, and where it is attained:")
for k, x in r["largest_at_cap"].items():
    P(f"    {k}: {x['value']:g}  ({x['where'].split('; ')[-1]})")
P(f"    behavioural draws on which the near-scope constraint is unreachable, largest count over logs and comparisons: {r['unreachable_draws_max']}")
open(V + "/out/table.txt", "w").write("\n".join(L) + "\n")
print("\n".join(L[:14]))
print("... lines:", len(L))
